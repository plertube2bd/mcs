using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Mcs.Compiler;

/// <summary>
/// Generates docs/api.md (`mcs --api-docs`) from the built-in declarations in <see cref="Prelude.Source"/>,
/// so the API reference always matches what the compiler accepts. tests/run.py fails when the file is stale.
/// </summary>
public static class ApiDocs
{
    static readonly Dictionary<string, string> Libraries = new()
    {
        ["MCS"] = "Core — always available",
        [""] = "Core — always available (`m.*`)",
    };

    public static string Generate()
    {
        var root = CSharpSyntaxTree.ParseText(Prelude.Source).GetCompilationUnitRoot();
        var sb = new StringBuilder();
        sb.AppendLine("# MC# API Reference (generated)");
        sb.AppendLine();
        sb.AppendLine("<!-- Generated by `mcs --api-docs > docs/api.md` from src/Mcs.Compiler/Prelude.cs. Do not edit by hand. -->");
        sb.AppendLine();
        sb.AppendLine("Every built-in type and member, exactly as the compiler declares it: parameter names, default values and");
        sb.AppendLine("every enum value. Explanations and examples are in the [library reference](libraries.md); the precise rules");
        sb.AppendLine("are in the [specification](ko/spec.md).");
        sb.AppendLine();
        sb.AppendLine("- `Milli` is shown for `float` and `Q16` for `double` (they are the same types).");
        sb.AppendLine("- `object` parameters take an entity object or an entity reference unless the comment says otherwise.");
        sb.AppendLine("- `// since X` marks members that need Minecraft X or later; using them on older targets is a compile error.");
        sb.AppendLine("- Block classes (`Stone`, `OakStairs`, …) and `EntityType` are generated per version from game data and are not listed.");
        sb.AppendLine();

        var sections = new List<(string ns, List<MemberDeclarationSyntax> types)>();
        foreach (var m in root.Members)
        {
            if (m is BaseNamespaceDeclarationSyntax n) sections.Add((n.Name.ToString(), n.Members.ToList()));
            else if (sections.Count > 0 && sections[^1].ns == "") sections[^1].types.Add(m);
            else sections.Add(("", [m]));
        }

        sb.AppendLine("## Contents");
        sb.AppendLine();
        foreach (var (ns, _) in sections) sb.AppendLine($"- [{Title(ns)}](#{Anchor(Title(ns))})");
        sb.AppendLine();

        foreach (var (ns, types) in sections)
        {
            sb.AppendLine($"## {Title(ns)}");
            sb.AppendLine();
            if (ns is not ("" or "MCS")) sb.AppendLine($"Load with `use {ns};`.\n");
            var attrs = types.OfType<ClassDeclarationSyntax>().Where(IsAttribute).ToList();
            foreach (var (title, group) in new[] {
                ("Attributes", attrs.Where(a => !Internal.Contains(a.Identifier.ValueText)).ToList()),
                ("Attributes for library authors (used in Prelude.cs)", attrs.Where(a => Internal.Contains(a.Identifier.ValueText)).ToList()) })
            {
                if (group.Count == 0) continue;
                sb.AppendLine($"### {title}");
                sb.AppendLine();
                sb.AppendLine("```csharp");
                foreach (var a in group) sb.Append(RenderAttribute(a));
                sb.AppendLine("```");
                sb.AppendLine();
            }
            foreach (var t in types.OfType<BaseTypeDeclarationSyntax>().Where(t => !IsAttribute(t) && IsPublic(t)))
            {
                sb.AppendLine($"### {t.Identifier.ValueText}");
                sb.AppendLine();
                sb.AppendLine("```csharp");
                sb.Append(RenderType(t, ""));
                sb.AppendLine("```");
                sb.AppendLine();
            }
        }
        return sb.ToString().TrimEnd() + "\n";
    }

    static readonly HashSet<string> Internal = ["IntrinsicAttribute", "NbtAttribute", "McAttributeAttribute", "McIdAttribute", "StateAttribute", "SinceAttribute"];

    static string Title(string ns) => Libraries.TryGetValue(ns, out var t) ? t : ns;
    static string Anchor(string title) => Regex.Replace(title.ToLowerInvariant().Replace(' ', '-'), "[^a-z0-9_-]", "");

    static bool IsAttribute(BaseTypeDeclarationSyntax t) =>
        t is ClassDeclarationSyntax c && c.Identifier.ValueText.EndsWith("Attribute") && c.BaseList?.Types.Any(b => b.ToString() == "System.Attribute") == true;

    static bool IsPublic(MemberDeclarationSyntax m) => m.Modifiers.Any(SyntaxKind.PublicKeyword);

    /// The `///` lines before a declaration, as `/// …` lines with the given indent.
    static string Doc(SyntaxNode n, string indent)
    {
        var sb = new StringBuilder();
        foreach (var tr in n.GetLeadingTrivia())
            if (tr.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia))
                foreach (var line in tr.ToFullString().Split('\n'))
                {
                    var l = line.Trim();
                    if (l.StartsWith("///")) l = l[3..].Trim();
                    if (l.Length > 0) sb.AppendLine($"{indent}/// {l}");
                }
        return sb.ToString();
    }

    static string? Since(MemberDeclarationSyntax m) =>
        m.AttributeLists.SelectMany(l => l.Attributes).Where(a => a.Name.ToString() is "Since" or "MCS.Since")
            .Select(a => a.ArgumentList?.Arguments.LastOrDefault()?.ToString().Trim('"')).FirstOrDefault();

    static string Clean(string s)
    {
        s = Regex.Replace(s, @"\s+", " ");
        s = Regex.Replace(s, @"\bfloat\b", "Milli");
        s = Regex.Replace(s, @"\bdouble\b", "Q16");
        s = Regex.Replace(s, @"\bSystem\.Collections\.Generic\.", "");
        s = Regex.Replace(s, @"\bSystem\.(Action|Func)\b", "$1");
        s = Regex.Replace(s, @"\bMCS\.", "");
        return s.Trim();
    }

    static string RenderAttribute(ClassDeclarationSyntax a)
    {
        string name = a.Identifier.ValueText[..^"Attribute".Length];
        var ctors = a.Members.OfType<ConstructorDeclarationSyntax>().Select(c => Clean(c.ParameterList.ToString())).ToList();
        var props = a.Members.OfType<PropertyDeclarationSyntax>().Select(p => $"{p.Identifier.ValueText} = …").ToList();
        string args = ctors.Count == 0 ? "" : ctors[0] == "()" ? "" : ctors[0];
        if (props.Count > 0) args = (args.Length == 0 ? "(" : args.TrimEnd(')') + ", ") + string.Join(", ", props) + ")";
        return Doc(a, "") + $"[{name}{args}]\n";
    }

    static string RenderType(BaseTypeDeclarationSyntax t, string indent)
    {
        var sb = new StringBuilder();
        sb.Append(Doc(t, indent));
        string mods = string.Join(" ", t.Modifiers.Select(m => m.ValueText));
        if (t is EnumDeclarationSyntax e)
        {
            bool docs = e.Members.Any(m => Doc(m, "").Length > 0);
            if (!docs) sb.AppendLine($"{indent}{mods} enum {e.Identifier.ValueText} {{ {string.Join(", ", e.Members.Select(m => m.ToString().Trim()))} }}");
            else
            {
                sb.AppendLine($"{indent}{mods} enum {e.Identifier.ValueText}\n{indent}{{");
                foreach (var m in e.Members) sb.Append(Doc(m, indent + "    ")).AppendLine($"{indent}    {m.Identifier.ValueText}{(m.EqualsValue != null ? " " + m.EqualsValue : "")},");
                sb.AppendLine($"{indent}}}");
            }
            return sb.ToString();
        }
        var td = (TypeDeclarationSyntax)t;
        string kind = td switch { StructDeclarationSyntax => "struct", InterfaceDeclarationSyntax => "interface", RecordDeclarationSyntax => "record", _ => "class" };
        string head = $"{mods} {kind} {td.Identifier.ValueText}{td.TypeParameterList}";
        if (td.BaseList != null) head += " " + td.BaseList.ToString().Trim();
        foreach (var c in td.ConstraintClauses) head += " " + c.ToString().Trim();
        var members = td.Members.Where(m => Visible(m, td)).ToList();
        if (members.Count == 0) { sb.AppendLine($"{indent}{Clean(head)} {{ }}"); return sb.ToString(); }
        sb.AppendLine($"{indent}{Clean(head)}\n{indent}{{");
        foreach (var m in members)
        {
            if (m is BaseTypeDeclarationSyntax nested) { sb.Append(RenderType(nested, indent + "    ")); continue; }
            sb.Append(Doc(m, indent + "    "));
            string? since = Since(m);
            sb.AppendLine($"{indent}    {Signature(m)}{(since != null ? $"   // since {since}" : "")}");
        }
        sb.AppendLine($"{indent}}}");
        return sb.ToString();
    }

    static bool Visible(MemberDeclarationSyntax m, TypeDeclarationSyntax owner)
    {
        if (owner is not InterfaceDeclarationSyntax && !IsPublic(m)) return false;
        string? name = m switch
        {
            MethodDeclarationSyntax md => md.ExplicitInterfaceSpecifier != null ? null : md.Identifier.ValueText,
            _ => "",
        };
        if (name == null) return false;
        if (m is MethodDeclarationSyntax { Modifiers: var mods } && mods.Any(SyntaxKind.OverrideKeyword)) return false;   // Equals / GetHashCode
        if (name is "GetEnumerator" || name.StartsWith("__")) return false;
        return true;
    }

    static string Signature(MemberDeclarationSyntax m)
    {
        SyntaxNode s = m.WithAttributeLists(default).WithoutTrivia();
        s = s switch
        {
            MethodDeclarationSyntax x => x.WithBody(null).WithExpressionBody(null).WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)),
            ConstructorDeclarationSyntax x => x.WithBody(null).WithExpressionBody(null).WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)),
            OperatorDeclarationSyntax x => x.WithBody(null).WithExpressionBody(null).WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)),
            ConversionOperatorDeclarationSyntax x => x.WithBody(null).WithExpressionBody(null).WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)),
            PropertyDeclarationSyntax x => x.WithExpressionBody(null).WithSemicolonToken(default).WithInitializer(null).WithAccessorList(Accessors(x.AccessorList, x.ExpressionBody != null)),
            IndexerDeclarationSyntax x => x.WithExpressionBody(null).WithSemicolonToken(default).WithAccessorList(Accessors(x.AccessorList, x.ExpressionBody != null)),
            _ => s,
        };
        return Clean(s.NormalizeWhitespace().ToFullString());
    }

    static AccessorListSyntax Accessors(AccessorListSyntax? list, bool getterOnly)
    {
        var acc = getterOnly || list == null
            ? [SyntaxFactory.AccessorDeclaration(SyntaxKind.GetAccessorDeclaration).WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken))]
            : list.Accessors.Select(a => a.WithBody(null).WithExpressionBody(null).WithAttributeLists(default).WithSemicolonToken(SyntaxFactory.Token(SyntaxKind.SemicolonToken)));
        return SyntaxFactory.AccessorList(SyntaxFactory.List(acc));
    }
}
